// Player movement: acceleration, friction, gravity, crouch and jump, on the
// shared body physics. Stopping to aim pays: spread grows with ground speed.
import { createBody, stepBody, groundSpeed, bodyBlocked } from './physics.js';

const STAND_HEIGHT = 1.72;
const CROUCH_HEIGHT = 1.12;
const STAND_EYE = 1.6;
const CROUCH_EYE = 1.02;
const WALK_SPEED = 5.2;
const CROUCH_SPEED = 2.4;
const JUMP_SPEED = 6.2;

export function createPlayer(colliders) {
  const body = createBody(0, 11.5, STAND_HEIGHT);

  function look(dx, dy, sensitivity = 0.0022) {
    body.yaw -= dx * sensitivity;
    body.pitch = Math.max(-1.45, Math.min(1.45, body.pitch - dy * sensitivity));
  }

  function recoil(pitchKick, yawKick) {
    body.pitch = Math.min(1.45, body.pitch + pitchKick);
    body.yaw += yawKick;
  }

  function step(dt, keys) {
    const crouching = keys.has('ControlLeft') || keys.has('ControlRight') || keys.has('KeyC');
    if (crouching && !body.crouching) {
      body.crouching = true;
      body.height = CROUCH_HEIGHT;
    } else if (!crouching && body.crouching && !bodyBlocked(body, colliders, body.position.x, body.position.y, body.position.z, STAND_HEIGHT)) {
      body.crouching = false;
      body.height = STAND_HEIGHT;
    }
    const eyeTarget = body.crouching ? CROUCH_EYE : STAND_EYE;
    body.eye += (eyeTarget - body.eye) * Math.min(1, dt * 12);

    const forward = (keys.has('KeyW') ? 1 : 0) - (keys.has('KeyS') ? 1 : 0);
    const strafe = (keys.has('KeyD') ? 1 : 0) - (keys.has('KeyA') ? 1 : 0);
    let wishX = 0;
    let wishZ = 0;
    if (forward || strafe) {
      const sin = Math.sin(body.yaw);
      const cos = Math.cos(body.yaw);
      wishX = -sin * forward + cos * strafe;
      wishZ = -cos * forward - sin * strafe;
      const len = Math.hypot(wishX, wishZ) || 1;
      wishX /= len;
      wishZ /= len;
    }
    if (keys.has('Space') && body.onGround) {
      body.velocity.y = JUMP_SPEED;
      body.onGround = false;
    }
    const speed = body.crouching ? CROUCH_SPEED : WALK_SPEED;
    stepBody(body, colliders, dt, wishX, wishZ, speed, body.onGround ? 42 : 9, 9);
  }

  return {
    state: body,
    step,
    look,
    recoil,
    groundSpeed() {
      return groundSpeed(body);
    },
    reset(x, z, yaw = 0) {
      body.position.set(x, 0, z);
      body.velocity.set(0, 0, 0);
      body.yaw = yaw;
      body.pitch = 0;
      body.crouching = false;
      body.height = STAND_HEIGHT;
      body.eye = STAND_EYE;
      body.onGround = true;
    },
  };
}
